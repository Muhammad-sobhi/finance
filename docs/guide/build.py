import base64, html, pathlib
here = pathlib.Path(__file__).parent
root = here.parent.parent

def img(name):
    p = here / 'shots' / f'{name}.jpg'
    return f'data:image/jpeg;base64,{base64.b64encode(p.read_bytes()).decode()}' if p.exists() else ''

def shot(name, cap, phone=False):
    src = img(name)
    if not src:
        return ''
    return f'<figure class="{"ph" if phone else "dk"}"><img src="{src}"><figcaption>{cap}</figcaption></figure>'

def phones(*items):
    return '<div class="phones">' + ''.join(shot(n, c, True) for n, c in items) + '</div>'

def steps(*items):
    return '<ol class="steps">' + ''.join(f'<li>{s}</li>' for s in items) + '</ol>'

def tip(text):
    return f'<div class="tip"><b>نصيحة:</b> {text}</div>'

def note(text):
    return f'<div class="note">{text}</div>'

